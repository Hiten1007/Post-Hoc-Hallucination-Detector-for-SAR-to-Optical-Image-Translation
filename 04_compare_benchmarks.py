"""
Multi-Model Hallucination Benchmark Comparison
Reads the per-model benchmark CSVs and generates a combined comparison table and bar chart.

Usage:
    python3 04_compare_benchmarks.py

Expects these files to exist (generated by 03_evaluate_hallucinations.py --model <name>):
    - hallucination_benchmark_pix2pix.csv
    - hallucination_benchmark_cyclegan.csv
    - hallucination_benchmark_palette.csv
"""

import os
import sys
import pandas as pd
import matplotlib
matplotlib.use('Agg')  # Non-interactive backend for servers without displays
import matplotlib.pyplot as plt
import numpy as np

# IGBP Class Names
CLASS_NAMES = [
    "Evergreen Needleleaf Forest", "Evergreen Broadleaf Forest",
    "Deciduous Needleleaf Forest", "Deciduous Broadleaf Forest",
    "Mixed Forest", "Closed Shrublands", "Open Shrublands",
    "Woody Savannas", "Savannas", "Grasslands", "Permanent Wetlands",
    "Croplands", "Urban and Built-up", "Cropland/Natural Veg. Mosaics",
    "Snow and Ice", "Barren or Sparsely Vegetated", "Water Bodies"
]

MODEL_FILES = {
    "Pix2Pix": "hallucination_benchmark_pix2pix.csv",
    "CycleGAN": "hallucination_benchmark_cyclegan.csv",
    "Palette (DDPM)": "hallucination_benchmark_palette.csv",
}

MODEL_COLORS = {
    "Pix2Pix": "#2196F3",       # Blue
    "CycleGAN": "#FF9800",      # Orange
    "Palette (DDPM)": "#4CAF50", # Green
}


def load_benchmarks():
    """Load all available benchmark CSVs."""
    data = {}
    for model_name, csv_file in MODEL_FILES.items():
        if os.path.exists(csv_file):
            df = pd.read_csv(csv_file)
            data[model_name] = df
            print(f"✓ Loaded {csv_file} ({len(df)} classes)")
        else:
            print(f"✗ Skipping {model_name} (file not found: {csv_file})")

    if not data:
        print("\nERROR: No benchmark CSV files found! Run 03_evaluate_hallucinations.py first.")
        sys.exit(1)

    return data


def build_comparison_table(data):
    """Build a single combined table with hallucination rates from all models."""
    # Start with class IDs and names
    comparison = pd.DataFrame({
        "Class ID": range(17),
        "Land Cover Type": CLASS_NAMES,
    })

    for model_name, df in data.items():
        comparison[f"{model_name} Hall. Rate (%)"] = df["Hallucination Rate (%)"].values

    # Add a summary row with weighted averages
    summary = {"Class ID": "", "Land Cover Type": "WEIGHTED AVERAGE"}
    for model_name, df in data.items():
        total_valid = df["Valid Audited Pixels"].sum()
        total_hall = df["Hallucinated Pixels"].sum()
        weighted_avg = (total_hall / total_valid * 100) if total_valid > 0 else 0.0
        summary[f"{model_name} Hall. Rate (%)"] = round(weighted_avg, 2)

    comparison = pd.concat([comparison, pd.DataFrame([summary])], ignore_index=True)

    return comparison


def plot_comparison_chart(data, output_path="hallucination_comparison_chart.png"):
    """Generate a grouped bar chart comparing hallucination rates across models."""
    # Filter to only classes that have data (non-zero valid pixels in at least one model)
    active_classes = []
    for c in range(17):
        has_data = False
        for model_name, df in data.items():
            if df.iloc[c]["Valid Audited Pixels"] > 0:
                has_data = True
                break
        if has_data:
            active_classes.append(c)

    class_labels = [CLASS_NAMES[c] for c in active_classes]
    n_classes = len(active_classes)
    n_models = len(data)

    fig, ax = plt.subplots(figsize=(18, 8))

    bar_width = 0.8 / n_models
    x = np.arange(n_classes)

    for i, (model_name, df) in enumerate(data.items()):
        rates = [df.iloc[c]["Hallucination Rate (%)"] for c in active_classes]
        offset = (i - n_models / 2 + 0.5) * bar_width
        bars = ax.bar(x + offset, rates, bar_width, label=model_name,
                      color=MODEL_COLORS.get(model_name, f"C{i}"), alpha=0.85, edgecolor='white')

        # Add value labels on top of each bar
        for bar, rate in zip(bars, rates):
            if rate > 0:
                ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.8,
                        f'{rate:.1f}', ha='center', va='bottom', fontsize=6, fontweight='bold')

    ax.set_xlabel("IGBP Land Cover Class", fontsize=12, fontweight='bold')
    ax.set_ylabel("Hallucination Rate (%)", fontsize=12, fontweight='bold')
    ax.set_title("SAR-to-Optical Hallucination Benchmark:\nPix2Pix vs. CycleGAN vs. Palette (Diffusion)",
                 fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(class_labels, rotation=45, ha='right', fontsize=8)
    ax.legend(fontsize=11, loc='upper left')
    ax.set_ylim(0, 105)
    ax.grid(axis='y', alpha=0.3)

    plt.tight_layout()
    plt.savefig(output_path, dpi=200, bbox_inches='tight')
    print(f"\n✓ Comparison chart saved to: {output_path}")


def main():
    print("=" * 70)
    print("  MULTI-MODEL HALLUCINATION BENCHMARK COMPARISON")
    print("=" * 70)

    data = load_benchmarks()

    # Build and save combined table
    comparison = build_comparison_table(data)

    csv_output = "hallucination_comparison.csv"
    comparison.to_csv(csv_output, index=False)

    # Print the table beautifully
    pd.set_option('display.max_rows', None)
    pd.set_option('display.width', 1000)
    pd.set_option('display.max_columns', None)
    print("\n" + comparison.to_string(index=False))
    print(f"\n✓ Combined comparison table saved to: {csv_output}")

    # Generate bar chart
    plot_comparison_chart(data)

    # Summary statistics
    print("\n" + "=" * 70)
    print("  SUMMARY: Overall Weighted Average Hallucination Rates")
    print("=" * 70)
    for model_name, df in data.items():
        total_valid = df["Valid Audited Pixels"].sum()
        total_hall = df["Hallucinated Pixels"].sum()
        weighted_avg = (total_hall / total_valid * 100) if total_valid > 0 else 0.0
        print(f"  {model_name:20s} : {weighted_avg:6.2f}%")
    print("=" * 70)


if __name__ == "__main__":
    main()
